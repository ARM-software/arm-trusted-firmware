/*
 * Branch/PLL enable-vote field-mask helpers used by the configuration data.
 * VOTE*(x) yields a { addr, mask } pair for a struct clock_register_mask.
 * PLL_VOTE(x) yields an { addr, mask } pair for the PLL branch ENA vote.
 */
