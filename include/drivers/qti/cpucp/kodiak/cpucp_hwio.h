#ifndef QTI_CPUCP_HWIO_H
#define QTI_CPUCP_HWIO_H

#include <lib/utils_def.h>

/* Shared data and secure SCMI channel in the EPSS data memory. */
#define CPUCP_SHARED_DATA_BASE			(0x18508000U)
#define CPUCP_IPC_SEC_BUF_BASE			(0x18509000U)

/* APSS -> CPUCP doorbell. Writing the OSM_IPC bit raises the IRQ. */
#define APSS_SHARED_TZ_IPC_INTERRUPT_ADDR	(0x17c00008U)
#define APSS_SHARED_TZ_IPC_INTERRUPT_OSM_IPC_SHFT	(28U)

#define EPSSFAST_EPSS_MUC_CLK_CTRL		(0x18580000U)
#define EPSS_MUC_CLK_CTRL_CORE_CLK_EN		BIT_32(1)
#define EPSSTOP_SECURE_ACCESS_OVERRIDE		(0x18598000U)
#define EPSSTOP_SECURE_ACCESS_OVERRIDE_EN	BIT_32(0)
#define EPSSTOP_GLOBAL_ENABLE			(0x18598004U)
#define EPSSTOP_MUC_HANG_DET_CTRL		(0x18598010U)
#define EPSSTOP_MUC_HANG_DET_CTRL_IRQ_EN	BIT_32(0)
#define EPSSTOP_MUC_HANG_COUNT_THRESHOLD	(0x18598018U)
#define EPSSTOP_L3_VOTING_EN			(0x18598024U)

/* APSS clock dividers and muxes; mux input 1 is GPLL0 (600 MHz). */
#define APSS_LMH_GFMUX_CFG			(0x182a000cU)
#define APSS_LMH_CDIV_COUNT			(0x182a0010U)
#define APSS_PERIPHCLK_GFMUX_CFG		(0x182a005cU)
#define APSS_PERIPH_CDIV_COUNT			(0x182a0060U)
#define APSS_OSM_GFMUX_CFG			(0x182a007cU)
#define APSS_OSM_CDIV_COUNT			(0x182a0080U)
#define APSS_IPM_GFMUX_CFG			(0x182a008cU)
#define APSS_IPM_CDIV_COUNT			(0x182a0090U)
#define APSS_AHB_CLK_CFG			(0x182a00b0U)

#define TCSR_SOC_HW_VERSION			(0x01fc8000U)
#define QFPROM_RAW_PTE_ROW1_MSB			(0x0078018cU)
#define QFPROM_RAW_CALIBRATION_ROW12_MSB	(0x007802dcU)
#define QFPROM_RAW_QC_SPARE_21_MSB		(0x0078070cU)
#define QFPROM_CORR_PTE_ROW0_LSB		(0x00784180U)
#define QFPROM_CORR_FEATURE_CONFIG_NM_ROW2_LSB	(0x00784210U)
#define QFPROM_CORR_CALIBRATION_ROW_LSB(n)	(0x00784278U + ((n) * 8U))
#define QFPROM_CORR_CALIBRATION_ROW_MSB(n)	(0x0078427cU + ((n) * 8U))

#endif /* QTI_CPUCP_HWIO_H */
